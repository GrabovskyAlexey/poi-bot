package ru.grabovsky.poibot.service.interfaces

/** Данные пользователя: выгрузка и полное удаление (`/deleteme`). */
interface UserDataService {

    /** Все данные пользователя (профиль, места, свои оценки и комментарии) в виде JSON-файла. */
    fun export(userId: Long): ByteArray

    /**
     * Удаляет пользователя вместе с местами, публикациями, ссылками, оценками, комментариями, жалобами и состоянием диалогов.
     * Места, на которые больше никто не ссылается, удаляются; те, что нужны чужим оценкам и комментариям, остаются без привязки к автору.
     */
    fun deleteAll(userId: Long)
}
